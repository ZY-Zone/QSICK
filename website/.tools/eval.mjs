import { writeFileSync } from "node:fs";
const endpoint = "http://127.0.0.1:9222";
const version = await (await fetch(endpoint + "/json/version")).json();
const ws = new WebSocket(version.webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
let id = 1; const pending = new Map();
ws.onmessage = ev => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.rej(new Error(JSON.stringify(m.error))) : p.res(m.result); } };
const send = (method, params = {}, sessionId) => { const i = id++; ws.send(JSON.stringify({ id: i, method, params, sessionId })); return new Promise((res, rej) => pending.set(i, { res, rej })); };
const { targetId } = await send("Target.createTarget", { url: "about:blank" });
const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
const P = (m, p) => send(m, p, sessionId);
await P("Page.enable"); await P("Runtime.enable"); await P("Network.enable"); await P("Network.setCacheDisabled", { cacheDisabled: true });
await P("Page.navigate", { url: "http://127.0.0.1:8899/QSICK/" });
await new Promise(r => setTimeout(r, 2500));
const ev = await P("Runtime.evaluate", { expression: `(() => {
  const el = document.querySelector('.hero-title .grad-text');
  const cs = el ? getComputedStyle(el) : null;
  const sheets = [...document.styleSheets].map(s => { try { return [...s.cssRules].filter(r => r.cssText && r.cssText.includes('hero-title')).map(r => r.cssText); } catch(e){ return []; } });
  return JSON.stringify({ bg: cs && cs.backgroundImage, bgSize: cs && cs.backgroundSize, sheets, lastRule: sheets.flat().slice(-3) });
})()`, returnByValue: true });
console.log(JSON.parse(ev.result.value).bg);
console.log(JSON.parse(ev.result.value).bgSize);
console.log(JSON.stringify(JSON.parse(ev.result.value).sheets, null, 1).slice(0, 3000));
ws.close(); process.exit(0);
